/** 从数组里随便挑一个。 */
function pick<T>(items: T[]): T {
  return items[Math.floor(Math.random() * items.length)];
}

/**
 * 随机拼一段"看起来像开题、其实什么都没说"的提纲。
 *
 * 用途很明确：验证这套系统不会被凑数的文字骗过去。
 * 一份没写样本量、没写方法名、没写出处的提纲，
 * 纵轴分数就该很低 —— 不管它读起来多像模像样。
 *
 * 为什么不用真随机词：真随机词拼出来的是乱码，模型会直接报"这不是提纲"，
 * 那就测不到「文字通顺但内容空洞」这一种情况，而这一种恰恰是最常见的。
 */
export function randomOutline(): string {
  const major = pick(RANDOM_MAJORS);
  const ability = pick(RANDOM_ABILITIES);
  const method = pick(RANDOM_METHODS);
  const course = pick(RANDOM_COURSES);
  const method2 = pick(RANDOM_METHODS);

  return `一、研究背景
${major}专业的学生在${ability}上普遍存在不足，课堂上教师以讲授为主，学生动手机会有限，毕业后进入岗位往往需要重新适应。
二、研究问题
如何通过${method}提升${major}专业学生的${ability}。
三、研究内容
1. 分析${major}专业${course}的教学现状与存在的问题。
2. 探索${method}融入${course}的具体方式。
3. 总结一套适合本校学生的教学策略。
四、研究方法
本研究拟采用${method2}，结合日常教学中的观察与反思，逐步形成教学方案。
五、预期成果
学生的${ability}得到明显提升，形成一套可推广的教学方案，并为同类学校提供参考。`;
}
