/**
 * 演示和调试用的几段预设提纲。
 *
 * 为什么要有这个文件：
 * 演示的时候每次手打一段开题提纲既慢又容易打错，而打错的那次往往正好在录视频。
 * 更麻烦的是「随机凑一段」这种测试 —— 想验证「乱写的东西不会被夸成好选题」，
 * 总得先能一键造出一段乱写的东西。
 *
 * 为什么放在 lib 而不是直接写进组件：
 * 这几段是数据不是界面，放在组件里会让那个文件越来越长；
 * 而且这些提纲将来可能被自检脚本拿去跑（比如验证「离线也能算出分数」）。
 *
 * 为什么是五条预设：
 * 五条各代表一种「开题写得怎么样」——
 * 一份研究设计具体到每个阶段怎么称重、谁来编码、信度多少（落在最高档）；
 * 一份研究设计写得很完整（样本量、量表出处、评分者一致性、数据条数都有）；
 * 一份有方法名但样本含糊；
 * 一份只有方法名、没有任何样本和出处；
 * 一份纯粹是观点和体会，连方法名都是"文献研究法"。
 * 五条正好铺开"从能过到过不了"的整个区间，再多就是凑数。
 *
 * 为什么全都是本科选题：
 * 这个产品面向的是大学生的开题和预答辩。之前四条写的是中职、高职，
 * 演示时观众第一眼看到"中职"会以为这是个职教专用工具，
 * 而实际上它对任何学科的开题都一视同仁。示例的作用是让人一眼看懂
 * "我的情况大概对应哪一种"，所以示例得贴住主要用户群。
 */

/** 一段预设提纲。 */
export type SampleOutline = {
  /** 按钮上显示的名字，四个字以内，窄面板里放得下 */
  name: string;
  /** 一句话说明这段提纲是用来演示什么的 */
  note: string;
  /**
   * 总体评分（0-100）：跟报告顶部那个数是**同一个公式**算出来的。
   *
   * 这个数以前是人工标的「完成度」，标完之后用户在同一个屏幕上看到
   * 「90」配「六红一绿」，只会觉得系统自相矛盾 —— 那是我第一版设计错了。
   * 现在它由 lib/score.ts 算：每条主张（100 − 别人做过）× 0.5 + 答得上来 × 0.5，
   * 再按固定刻度换算成显示分，最后取平均，查不到的不算。
   *
   * 五条都用真模型跑过，按新刻度重算是 76 / 67 / 60 / 48 / 23，
   * 单调递减，正好铺开「从能过到过不了」的整条区间。
   * 改任何一条提纲的正文，都必须重跑一遍改这个数 ——
   * 一个没跟着算法走的分数，比没有分数更糟。
   */
  quality: number;
  /** 提纲正文 */
  text: string;
};

/**
 * 「往输入框里填一段提纲」这个动作，走的是浏览器事件，不是组件 props。
 *
 * 为什么不直接把回调传给调试面板：
 * 调试面板挂在 app/layout.tsx 上（这样将来加别的页面它也自动都在），
 * 而输入框在 app/page.tsx 里。要让 layout 里的组件改 page 里的 state，
 * 就得把回调从 page 一路传到 layout —— 但 layout 是 page 的父组件，
 * 父传子这个方向反了，只能靠 context 或者全局状态。
 *
 * 一个自定义事件比 context 轻得多：谁想填就 dispatch，谁想接就 listen，
 * 中间不需要任何 Provider 包着，也不用为了一个调试功能改动组件树。
 * 代价是它不是类型安全的（事件名和载荷靠约定），所以两边共用下面这个常量，
 * 至少不会出现「发的时候叫 A、听的时候叫 B」。
 */
export const FILL_OUTLINE_EVENT = "pre-defense:fill-outline";

/** 请页面把这段提纲填进输入框。 */
export function requestFillOutline(text: string): void {
  window.dispatchEvent(new CustomEvent(FILL_OUTLINE_EVENT, { detail: text }));
}

