/* ---------- 分数档位 ---------- */

/**
 * 把一个总体评分归到三档，只用来决定按钮上那个数字的颜色深浅。
 *
 * 为什么按档而不是按具体数字生成 class：
 * 之前用的是 `dbg-action-q90` / `q60` / `q40` / `q20`，
 * 分数一改（90→50），样式就全落空，四个按钮变成同一个灰。
 * 档位是稳定的语义，具体数字会随着算法和提纲改，不该拿来当选择器。
 *
 * 为什么不按红黄绿三色：这四个分数描述的是「开题写得多完整」，
 * 不是「好/坏」的判决。40 分那份不是"错"，只是"还没写清楚"。
 * 红绿灯会让用户以为系统在给他打分，而它其实只是在描述现状。
 */
export type QualityBand = "high" | "mid" | "low";

export function qualityBand(quality: number): QualityBand {
  if (quality >= 60) return "high";
  if (quality >= 40) return "mid";
  return "low";
}

