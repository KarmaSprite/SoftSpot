/**
 * 站长开关。
 *
 * 为什么不用环境变量（.env.local）：
 *   1. 这个项目的 .env.local 只放一样东西 —— API key。混进功能开关，
 *      以后想知道"这个功能开没开"得去翻环境变量，还要记得重启。
 *   2. 开关放代码里，打开这个文件一眼就能看到全部可关的东西，
 *      改一个 true/false 保存即生效（Next 会热重载这个模块）。
 *   3. 部署给别人用时，改代码比让非技术用户改环境变量可靠。
 *
 * 这里只放**能整块拿掉的功能**，不放调参用的数字。
 * 数字（阈值、权重、分界线）散在各自的 lib 文件里，改它们要连带改自检，
 * 跟"这个功能要不要给用户看"是两件事，不该混在一起。
 */

export type SiteConfig = {
  /**
   * 「手工粘贴中文文献」这个功能开不开。
   *
   * 为什么要这个开关：知网没有面向个人的 API，英文库又基本查不到中文职教论文，
   * 所以让用户把自己手上已有的中文文献粘进来，是补上这块缺口的唯一办法。
   * 但它有两个副作用 —— 输入框会让首页变长，而且用户可能粘一堆不相关的标题
   * 把分数抬高。站长如果只想给用户看自动检索的结果，把这里改成 false 就行：
   * 首页不显示输入框，后端也会忽略前端传上来的内容（不会偷偷算进去）。
   *
   * 注意：后端也要判这个开关，不能只在前端藏输入框。
   * 前端藏起来只是不给入口，接口谁都能直接 POST。
   */
  manualRefs: boolean;
};

export const SITE: SiteConfig = {
  manualRefs: true,
};
